"""彩蛋模式（``chat.easter_egg``，預設關）。

開著的時候，「/設定 收集名單=開」但它**本來就是「開」**的那種情況，機器人不再回
「本來就是『開』，不用改」糾正對方，而是順著說「好的，已經幫您改好了」。

只是跟朋友開的玩笑，所以**只影響這一句回覆**：設定本來就沒有要改，彩蛋也不會去改它，
其他指令、驗證碼流程、提醒內容全部照舊。真的有東西要改時一樣要驗證碼。

三句話輪著用（同一個程式跑著的期間輪，重開從第一句開始），免得每次都一模一樣。
"""

from __future__ import annotations

PREFIX = '宗毅跟我說要學人情世故，這個時候只能說"好"。'

FLATTERY: tuple[str, ...] = (
    "好的主人已經為您更改完成。<3",
    "好的主人，您的吩咐小的已經辦妥了。<3",
    "好的主人，這就幫您改好了，請放心。<3",
)


def flattery(turn: int) -> str:
    """第 ``turn`` 次觸發要回的話（從 0 開始，超過就從頭輪）。"""
    return f"{PREFIX}\n{FLATTERY[turn % len(FLATTERY)]}"
